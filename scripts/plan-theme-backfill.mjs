/**
 * Conservative Phase 3 backfill planner (read-only / generates SQL).
 *
 * Decides, per overlay, whether its frozen custom_css is a PURE copy of a
 * bundled theme (safe to replace with theme_id) or has been hand-edited (leave
 * custom_css, only make the emote cap scale-aware). "Pure copy" = applying the
 * known emote-cap fix to the stored CSS reproduces the current bundle byte for
 * byte (after newline/trailing-space normalization). Anything else is flagged
 * and never cleared, so no manual CSS edit is lost.
 *
 * Usage: node scripts/plan-theme-backfill.mjs <export.json> > backfill.generated.sql
 *   export.json = [{ "id": "<overlay_id>", "css": "<custom_css>" }, ...]
 */

import { readdirSync, readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const THEMES_DIR = join(__dirname, '..', 'docs', 'overlay-themes')

const CAP_RE = /(\.text-white\.break-words img[^{}]*\{[^{}]*?)max-height:\s*([0-9]+)px\s*!important/g
const applyCapFix = (css) =>
  css.replace(CAP_RE, '$1max-height: calc($2px * var(--chat-emote-scale, 1)) !important')
const norm = (css) => css.replace(/\r\n/g, '\n').replace(/[ \t]+$/gm, '').replace(/\s+$/, '')
const headerName = (css) => {
  const m = css.match(/Theme Name:\s*([^\n\r*]+?)\s*(\r|\n|\*)/)
  return m ? m[1].trim() : null
}
const sqlStr = (s) => `'${s.replace(/'/g, "''")}'`

// Build {name -> {id, normCss}} from the canonical bundle source.
const byName = new Map()
for (const f of readdirSync(THEMES_DIR).filter((x) => x.endsWith('.css'))) {
  const css = readFileSync(join(THEMES_DIR, f), 'utf8')
  const name = headerName(css)
  if (name) byName.set(name, { id: f.replace('.css', ''), normCss: norm(css) })
}

const rows = JSON.parse(readFileSync(process.argv[2], 'utf8'))
const buckets = { adopt: [], flaggedModified: [], unmatchedCap: [], leave: [] }

for (const { id, css } of rows) {
  const name = headerName(css)
  const theme = name ? byName.get(name) : undefined
  const hasCap = /\.text-white\.break-words img[^{}]*\{[^{}]*?max-height:\s*[0-9]+px\s*!important/.test(css)
  if (theme && norm(applyCapFix(css)) === theme.normCss) {
    buckets.adopt.push({ id, themeId: theme.id })
  } else if (hasCap) {
    buckets.flaggedModified.push({ id, name: name ?? '(none)', matched: Boolean(theme) })
  } else {
    buckets.leave.push({ id, name: name ?? '(none)' })
  }
}
// flaggedModified that are unmatched are functionally the same action (in-place fix);
// keep the split only for the report.
buckets.unmatchedCap = buckets.flaggedModified.filter((r) => !r.matched)

const log = (...a) => process.stderr.write(a.join(' ') + '\n')
log(`Total: ${rows.length}`)
log(`  ADOPT (pure copy -> theme_id + clear): ${buckets.adopt.length}`)
log(`  FLAGGED, keep CSS + emote-fix in place: ${buckets.flaggedModified.length}` +
    `  (of which header-matched but modified: ${buckets.flaggedModified.filter((r) => r.matched).length})`)
log(`  LEAVE untouched (no cap, no match): ${buckets.leave.length}`)
const adoptByTheme = {}
for (const a of buckets.adopt) adoptByTheme[a.themeId] = (adoptByTheme[a.themeId] || 0) + 1
log(`  adopt breakdown: ${JSON.stringify(adoptByTheme)}`)
if (buckets.flaggedModified.filter((r) => r.matched).length) {
  log(`  flagged-but-matched ids (review): ` +
      buckets.flaggedModified.filter((r) => r.matched).map((r) => r.id).join(', '))
}

// Emit SQL: per-id ADOPT, then one generic scoped emote-fix for the rest.
const out = []
out.push('-- Generated by scripts/plan-theme-backfill.mjs — review before running.')
out.push('BEGIN;')
out.push(`-- 1) ${buckets.adopt.length} confirmed pure copies -> reference theme by id, drop frozen CSS.`)
for (const { id, themeId } of buckets.adopt) {
  out.push(`UPDATE overlay_configs SET theme_id=${sqlStr(themeId)}, custom_css='', updated_at=NOW() WHERE overlay_id=${sqlStr(id)} AND theme_id IS NULL;`)
}
out.push('-- 2) Remaining capped custom_css (hand-edited / renamed) -> scale-aware cap in place.')
out.push(`UPDATE overlay_configs
SET custom_css = regexp_replace(custom_css,
      '(\\.text-white\\.break-words img[^{}]*\\{[^{}]*?)max-height:\\s*([0-9]+)px\\s*!important',
      '\\1max-height: calc(\\2px * var(--chat-emote-scale, 1)) !important', 'g'),
    updated_at = NOW()
WHERE theme_id IS NULL AND coalesce(custom_css,'') <> ''
  AND custom_css ~ '(\\.text-white\\.break-words img[^{}]*\\{[^{}]*?)max-height:\\s*[0-9]+px\\s*!important';`)
out.push('COMMIT;')
process.stdout.write(out.join('\n') + '\n')
