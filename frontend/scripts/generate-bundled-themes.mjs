/**
 * Codegen: bundle the canonical overlay themes into the frontend build.
 *
 * Source of truth: ../docs/overlay-themes/*.css (also served via GitHub raw).
 * Output: src/lib/theme-marketplace/bundled-themes.generated.ts
 *
 * The generated file is COMMITTED so the production build does not need the
 * docs/ directory in its context. Re-run `npm run generate:themes` whenever a
 * theme changes; CI verifies the committed file is in sync (see the parity
 * test). Bundling — rather than copying theme CSS into each overlay's DB row —
 * is what lets a theme fix reach every overlay on the next deploy.
 */

import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const THEMES_DIR = join(__dirname, '..', '..', 'docs', 'overlay-themes')
const OUT_FILE = join(__dirname, '..', 'src', 'lib', 'theme-marketplace', 'bundled-themes.generated.ts')

/** Mirror of metadata-parser.ts parseThemeMetadata (kept in sync intentionally). */
function filenameToTitle(filename) {
  return filename
    .replace('.css', '')
    .replace(/-/g, ' ')
    .replace(/\b\w/g, (c) => c.toUpperCase())
}

function parseThemeMetadata(css, filename) {
  const match = css.match(/\/\*\*\s*([\s\S]*?)\s*\*\//)
  if (!match) {
    return { name: filenameToTitle(filename), description: 'No description available', tags: ['uncategorized'] }
  }
  const header = match[1]
  const extract = (field) => {
    const m = header.match(new RegExp(`\\*\\s*${field}:\\s*(.+)`, 'i'))
    return m ? m[1].trim() : ''
  }
  const tags = extract('Tags')
    .split(',')
    .map((t) => t.trim().toLowerCase())
    .filter(Boolean)
  return {
    name: extract('Theme Name') || filenameToTitle(filename),
    description: extract('Description') || 'No description available',
    tags: tags.length > 0 ? tags : ['uncategorized'],
    author: extract('Author') || undefined,
    version: extract('Version') || undefined,
    updated: extract('Updated') || undefined,
  }
}

const files = readdirSync(THEMES_DIR)
  .filter((f) => f.endsWith('.css'))
  .sort()

const themes = files.map((filename) => {
  const css = readFileSync(join(THEMES_DIR, filename), 'utf8')
  return { id: filename.replace('.css', ''), filename, css, ...parseThemeMetadata(css, filename) }
})

